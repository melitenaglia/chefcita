create or replace function private.normalize_ingredient_name(p_name text)
returns text
language sql
immutable
set search_path = ''
as $$
  select trim(
    regexp_replace(
      regexp_replace(
        translate(
          lower(trim(coalesce(p_name,''))),
          'áàäâãåéèëêíìïîóòöôõúùüûñç',
          'aaaaaaeeeeiiiiooooouuuunc'
        ),
        '[^a-z0-9]+',
        ' ',
        'g'
      ),
      '\s+',
      ' ',
      'g'
    )
  );
$$;

