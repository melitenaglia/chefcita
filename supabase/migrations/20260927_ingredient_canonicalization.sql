join public.ingredients target
  on private.normalize_ingredient_name(target.canonical_name)=private.normalize_ingredient_name(m.target_name)
on conflict (normalized_alias)
do update set ingredient_id=excluded.ingredient_id, alias_text=excluded.alias_text;

