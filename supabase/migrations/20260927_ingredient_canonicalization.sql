create or replace function private.canonicalize_ingredient_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_norm text;
  v_target public.ingredients;
begin
  v_norm:=private.normalize_ingredient_name(coalesce(new.canonical_name,new.normalized_name));

  select i.*
  into v_target
  from public.ingredient_aliases a
  join public.ingredients i on i.id=a.ingredient_id
  where a.normalized_alias=v_norm
  limit 1;

  if found then
    new.canonical_name:=v_target.canonical_name;
    new.normalized_name:=v_target.normalized_name;
  else
    new.canonical_name:=trim(new.canonical_name);
    new.normalized_name:=v_norm;
  end if;

  return new;
end;
$$;

drop trigger if exists ingredients_canonicalize_before_insert on public.ingredients;
create trigger ingredients_canonicalize_before_insert
before insert on public.ingredients
for each row execute function private.canonicalize_ingredient_insert();

