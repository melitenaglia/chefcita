select distinct m.target_name, private.normalize_ingredient_name(m.target_name)
from ingredient_merge_map m
where not exists (
  select 1
  from public.ingredients i
  where private.normalize_ingredient_name(i.canonical_name)=private.normalize_ingredient_name(m.target_name)
)
on conflict (normalized_name) do nothing;

